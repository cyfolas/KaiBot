//! Предметная логика бота — без обращений к Discord и базе, поэтому полностью покрыта тестами.
//!
//! Модули снизу вверх:
//! * [`permissions`] — каталог прав Discord: все биты, русские названия, категории, применимость
//!   к типам каналов, неявные следствия и уровни опасности;
//! * [`roles`] — классификация ролей по правам (администрация, управление, модерация…) и по
//!   происхождению (интеграция, бусты, подписки);
//! * [`hierarchy`] — иерархия ролей, план изменения состава администрации, положение бота;
//! * [`access`] — доступ к самому боту: режимы и правила;
//! * [`policy`] — политика прав сервера: модель, разбор текущего состояния, план приведения;
//! * [`text`] — укладывание текста в лимиты Discord.
//!
//! Команды и обработчики событий только собирают данные из Discord, вызывают эти функции и
//! исполняют полученное решение.

pub mod access;
pub mod hierarchy;
pub mod permissions;
pub mod policy;
pub mod roles;
pub mod text;
